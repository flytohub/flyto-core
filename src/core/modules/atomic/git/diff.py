logger = logging.getLogger(__name__)


async def _run_git(repo_path: str, *args: str) -> tuple:
    """Run a git command in the given repo and return (returncode, stdout, stderr)."""
    proc = await asyncio.create_subprocess_exec(
        'git', '-C', repo_path, *args,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    out, err = await proc.communicate()
    return proc.returncode, out.decode('utf-8', errors='replace'), err.decode('utf-8', errors='replace')


def _build_diff_args(staged: bool, ref1: str, ref2: str = None, extra_flags: List[str] = None) -> List[str]:
    """Build git diff argument list."""
    args: List[str] = ['diff']
    if staged:
        args.append('--cached')
    elif ref2:
        args.extend([ref1, ref2])
    else:
        args.append(ref1)
    if extra_flags:
        args.extend(extra_flags)
    return args


def _parse_numstat(numstat_out: str) -> tuple:
    """Parse git diff --numstat output into (files_changed, insertions, deletions)."""
    files_changed = 0
    insertions = 0
    deletions = 0
    if not numstat_out.strip():
        return files_changed, insertions, deletions
    for line in numstat_out.strip().split('\n'):
        parts = line.split('\t')
        if len(parts) >= 3:
            files_changed += 1
            try:
                insertions += int(parts[0])
            except ValueError:
                pass
            try:
                deletions += int(parts[1])
            except ValueError:
                pass
    return files_changed, insertions, deletions


def _refused(kind: str, detail: str, **fields: Any) -> Dict[str, Any]:
    """The envelope for a path that produced no diff.

    FAILED on every one. See the module docstring for why none of them is
    INDETERMINATE: a read that raises leaves no question about the world.
    """
    return envelope(
        Outcome.FAILED,
        claim_by=ClaimBy.NONE,
        effects=[dict({'kind': kind, 'measured_by': None, 'detail': detail}, **fields)],
    )


def _diff_outcome(
    *,
    repo_path: str,
    diff_out: str,
    files_changed: int,
    insertions: int,
    deletions: int,
    numstat_available: bool,
) -> Dict[str, Any]:
    """The rung this read earned; the decision is whether anything came back.

    `diff_out` is checked before `files_changed` because it is the payload the
    caller asked for and it is non-empty in cases numstat reports nothing --
    a pure mode change, for instance, has a diff header and no line counts.
    Either one being non-empty means git produced content describing the trees
    it walked.
    """
    if diff_out or files_changed:
        return envelope(
            Outcome.OBSERVED,
            claim_by=ClaimBy.NONE,
            effects=[{
                'kind': 'git_diff_returned',
                'repo_path': repo_path,
                'diff_characters': len(diff_out),
                'files_changed': files_changed,
                'insertions': insertions,
                'deletions': deletions,
                'numstat_available': numstat_available,
                'measured_by': (
                    'git diff output, with counts from a second git diff '
                    '--numstat over the same refs'
                ),
                'detail': (
                    'Content git generated from the trees named by the refs. An '
                    'observation of the repository as it is now, not a claim '
                    'that it will still say this a moment from now.'
                ),
            }],
        )

    return envelope(
        Outcome.ACCEPTED,
        claim_by=ClaimBy.NONE,
        effects=[{
            'kind': 'git_diff_empty',
            'repo_path': repo_path,
            'numstat_available': numstat_available,
            'measured_by': None,
            'detail': (
                'git exited 0 and produced no diff and no counts. That the '
                'command was taken and answered is all this says: an empty '
                'diff string reads identically whether the trees match, the '
                'pathspec matched nothing, or nothing was ever asked.'
            ),
        }],
    )


