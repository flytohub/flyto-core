async def git_diff(context: Dict[str, Any]) -> Dict[str, Any]:
    """Get git diff"""
    params = context['params']
    # SECURITY: the diff body is returned to the caller, so an unconfined
    # repo_path reads out any git tree on the host — the read side of
    # GHSA-wc94-386q-5478.
    repo_path = validate_path_with_env_config(str(params['repo_path']))
    ref1 = params.get('ref1', 'HEAD')
    ref2 = params.get('ref2')
    staged = params.get('staged', False)
    stat_only = params.get('stat_only', False)

    if not os.path.isdir(os.path.join(repo_path, '.git')):
        return {
            'ok': False,
            'error': f'Not a git repository: {repo_path}',
            'error_code': 'NOT_A_REPO',
            'outcome': _refused(
                'git_repo_absent',
                'No .git directory at this path, so no git process was started.',
                repo_path=repo_path,
            ),
        }

    try:
        diff_args = _build_diff_args(staged, ref1, ref2, ['--stat'] if stat_only else None)
        rc, diff_out, err = await _run_git(repo_path, *diff_args)
        if rc != 0:
            return {
                'ok': False,
                'error': f'git diff failed: {err.strip()}',
                'error_code': 'DIFF_FAILED',
                'outcome': _refused(
                    'git_diff_rejected',
                    'git diff exited non-zero -- an unknown ref or an unreadable '
                    'repository. No diff was produced.',
                    repo_path=repo_path,
                    exit_code=rc,
                ),
            }

        numstat_args = _build_diff_args(staged, ref1, ref2, ['--numstat'])
        rc, numstat_out, _ = await _run_git(repo_path, *numstat_args)
        numstat_available = rc == 0
        files_changed, insertions, deletions = (
            _parse_numstat(numstat_out) if numstat_available else (0, 0, 0)
        )

        logger.info(f"Git diff: {files_changed} files, +{insertions}/-{deletions}")
        return {
            'ok': True,
            'data': {
                'diff': diff_out,
                'files_changed': files_changed,
                'insertions': insertions,
                'deletions': deletions,
                'outcome': _diff_outcome(
                    repo_path=repo_path,
                    diff_out=diff_out,
                    files_changed=files_changed,
                    insertions=insertions,
                    deletions=deletions,
                    numstat_available=numstat_available,
                ),
            },
        }

    except FileNotFoundError:
        return {
            'ok': False,
            'error': 'git command not found. Ensure git is installed.',
            'error_code': 'GIT_NOT_FOUND',
            'outcome': _refused(
                'git_binary_absent',
                'The git executable could not be spawned, so nothing left this process.',
                repo_path=repo_path,
            ),
        }
    except Exception as e:
        logger.error(f"Git diff error: {e}")
        return {
            'ok': False,
            'error': str(e),
            'error_code': 'DIFF_ERROR',
            'outcome': _refused(
                'git_diff_raised',
                'An exception was raised while driving git diff. This module only '
                'reads, so the repository is unchanged and the only thing lost is '
                'the answer -- failed, not indeterminate.',
                repo_path=repo_path,
                error=f'{type(e).__name__}: {e}',
            ),
        }
