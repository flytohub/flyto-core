"""
Git Diff Module
Get git diff output with statistics

HOW FAR THIS MODULE FOLLOWS REALITY

`git.diff` is the odd one in the git group: it is side-effecting by category and
changes nothing. Its "effect" is the reading, so the question the ladder asks
becomes "is the answer in the payload, or only the report that an answer was
produced" -- which is the same question `dns.lookup` answers and gets the same
two rungs.

    diff text or a numstat line came back           OBSERVED
        `diff` holds bytes git generated by walking real trees, and
        `files_changed` counts tab-separated numstat records that came from the
        same walk. Both are content, not status.

    git exited 0 with nothing to say                ACCEPTED
        An empty diff is the honest floor and not a disappointment. `diff == ''`
        with `files_changed == 0` is byte-identical to what a module that never
        ran would return, so it cannot be evidence that anything was examined.
        What is known is that git took the request and answered, and that is
        what ACCEPTED means. A consumer wanting "there are definitely no
        changes" is asking for a rung this code does not reach.

    not a repo / git refused / git missing          FAILED
        Definite. No answer was produced and none is coming.

Every error path is FAILED and none is INDETERMINATE, which is the opposite of
`git.commit` and `git.clone` in this same package -- deliberately. Those two
write, so an exception mid-flight leaves a question about the world. This one
reads: when it raises, nothing happened to the repository and the only casualty
is the answer. There is nothing to be uncertain about.

A second git invocation produces the counts (`--numstat`), and it can fail on
its own while the first succeeded. That is recorded as `numstat_available`
rather than smoothed into a zero, for the reason `git.commit` records
`diffstat_available`: a count of 0 and a count that was never taken are
different facts, and one integer cannot hold both.
"""

