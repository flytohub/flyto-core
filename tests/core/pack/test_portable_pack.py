"""The portable pack: a ``standalone`` section, a generated build, and one zip artifact.

A connector pack built here runs on its own as an MCP server and loads into
a Space unchanged. These tests cover the manifest section, the build (entry
points, README and notice generated by core), the zip format and its
refusals, and the zero-coupling property of what a build ships.
"""

import ast
import copy
import hashlib
import json
import re
import stat
import zipfile

import pytest
from portable_helpers import EXAMPLE_DIR, LOCK, example_doc, example_source

from core.pack.manifest import (
    PackManifestError,
    manifest_sha256,
    read_pack_manifest,
    validate_pack_manifest,
)
from core.pack.portable import (
    ENTRY_ACTIONS,
    PLATFORMS,
    build_portable_pack,
    extract_pack_zip,
    verify_pack,
)


def code_of(call):
    with pytest.raises(PackManifestError) as info:
        call()
    return info.value.code


def built(tmp_path, *, name="ratings", **kwargs):
    source = kwargs.pop("source", None) or example_source(tmp_path, name=f"{name}-src")
    out = tmp_path / f"{name}.zip"
    report = build_portable_pack(source, out, lockfile=kwargs.pop("lockfile", LOCK), **kwargs)
    return out, report


def zip_names(path):
    with zipfile.ZipFile(path) as archive:
        return sorted(archive.namelist())


def zip_text(path, name):
    with zipfile.ZipFile(path) as archive:
        return archive.read(name).decode("utf-8")


# -- the standalone section ------------------------------------------------------------


def test_the_example_declares_a_standalone_section_and_core_derives_the_rest():
    standalone = read_pack_manifest(EXAMPLE_DIR)["standalone"]
    assert standalone["transports"] == ["stdio", "streamable_http"]
    assert standalone["runtime"] == {"language": "python", "version": ">=3.10", "package": "flyto-core"}
    assert standalone["lockfile"] == {"path": "requirements.lock", "format": "pip-require-hashes"}
    # Credential names come from connector.auth, never a value.
    assert standalone["credentials"] == [{
        "name": "ratings_api_token",
        "env": "FLYTO_CREDENTIAL_RATINGS_API_TOKEN",
        "keychain": {"service": "flyto.pack.com.example.ratings", "account": "ratings_api_token"},
    }]
    assert standalone["credentials_needed"] == "one_of"
    assert set(standalone["entry_points"]) == set(PLATFORMS) == {"macos", "linux", "windows"}
    for entry in standalone["entry_points"].values():
        assert set(entry) == set(ENTRY_ACTIONS) == {"install", "healthcheck", "serve"}
        assert set(entry["serve"]) == {"stdio", "streamable_http"}
    assert standalone["entry_points"]["macos"]["serve"]["stdio"] == [
        "sh", "bin/macos/serve.sh", "--transport", "stdio",
    ]
    assert standalone["entry_points"]["windows"]["install"] == ["cmd.exe", "/d", "/c", "bin\\windows\\install.cmd"]


def _set(path, value):
    def mutate(doc):
        target = doc
        for key in path[:-1]:
            target = target[key]
        target[path[-1]] = value
    return mutate


@pytest.mark.parametrize("mutate, code", [
    (_set(("standalone", "transports"), ["stdio", "websocket"]), "STANDALONE_TRANSPORT_UNKNOWN"),
    (_set(("standalone", "transports"), []), "INVALID_STANDALONE"),
    (_set(("standalone", "transports"), ["stdio", "stdio"]), "INVALID_STANDALONE"),
    (_set(("standalone", "credentials"), [{"name": "ratings_api_token"}]), "STANDALONE_DERIVED"),
    (_set(("standalone", "entry_points"), {"macos": {}}), "STANDALONE_DERIVED"),
    (_set(("standalone", "runtime"), {"language": "node", "version": ">=20.0"}), "STANDALONE_RUNTIME_UNSUPPORTED"),
    (_set(("standalone", "runtime"), {"language": "python", "version": "~3"}), "STANDALONE_RUNTIME_UNSUPPORTED"),
    (_set(("standalone", "lockfile"), "../requirements.lock"), "INVALID_STANDALONE"),
    (_set(("standalone", "lockfile"), "bin/requirements.lock"), "INVALID_STANDALONE"),
    (_set(("standalone", "healthcheck"), "curl https://example.invalid"), "UNKNOWN_KEY"),
])
def test_a_standalone_section_is_refused_with_a_typed_reason(mutate, code):
    assert code_of(lambda: validate_pack_manifest(example_doc(mutate))) == code


