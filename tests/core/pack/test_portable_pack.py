def test_the_pack_cli_builds_and_verifies_a_zip(tmp_path, capsys):
    import argparse

    from cli.pack import run_pack_command

    out = tmp_path / "cli.zip"
    build = argparse.Namespace(pack_action="build", pack_dir=str(example_source(tmp_path)), output=str(out),
                               lock=str(LOCK), key=None, key_id=None)
    assert run_pack_command(build) == 0
    built_report = json.loads(capsys.readouterr().out)
    assert built_report["zip"] == str(out)
    verify = argparse.Namespace(pack_action="verify", pack_dir=str(out), trusted_key=[], allow_unsigned=True,
                                revocations=None, revocation_key=[])
    assert run_pack_command(verify) == 0
    verified = json.loads(capsys.readouterr().out)
    assert verified["pack_digest"] == built_report["pack_digest"]
    assert verified["revocation"] == "no list configured"
    assert verified["module_ids"] == ["ratings.company.get", "ratings.findings.list", "ratings.portfolio.list"]
    # Without a lock the CLI refuses, with the typed reason.
    again = argparse.Namespace(pack_action="build", pack_dir=str(example_source(tmp_path, name="nolock")),
                               output=str(tmp_path / "nolock.zip"), lock=None, key=None, key_id=None)
    assert run_pack_command(again) == 1
    assert "LOCKFILE_MISSING" in capsys.readouterr().err
