            "verifier itself is non-actuating - no hardware, ROS, Gazebo, Lima, "
            "gateway, dispatch, cmd_vel publication, network, SSH or login action "
            "was taken, and subprocess execution plus outbound networking were "
            "disabled inside the verifying interpreter."
        ),
        "scope_flags": {
            "simulation_derived": True,
            "physical_hardware_evidence": False,
            "actuating": False,
            "dispatched_any_plan": False,
            "published_cmd_vel": False,
            "started_ros_gazebo_or_lima": False,
            "used_network_ssh_or_login": False,
        },
        "generated_at": finished.strftime("%Y-%m-%dT%H:%M:%S.%fZ"),
        "freshness": {
            "verifier_started_at": started_at.strftime("%Y-%m-%dT%H:%M:%S.%fZ"),
            "verifier_finished_at": finished.strftime("%Y-%m-%dT%H:%M:%S.%fZ"),
