INSTALL_COMMAND="pip install --no-index --no-deps --target <scratch>/target <wheel>"
note "installing the wheel offline into a throwaway target"
if ! "$PYTHON_BIN" -m pip install --no-index --no-deps --target "$TARGET" "$WHEEL_PATH" \
        >"$SCRATCH/install.log" 2>&1; then
