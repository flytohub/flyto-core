    finished = _dt.datetime.now(_dt.timezone.utc)

    wheel_path = cfg["wheel_path"]
    report = {
        "contract_version": CONTRACT,
        "passed": passed,
        "run_id": cfg["run_id"],
        "scope": (
            "Registration and declaration evidence for the flyto-modules-robotics "
            "wheel inside this flyto-core checkout, cross-checked against one "
            "finished Gazebo simulation run. Every physical claim restated here is "
