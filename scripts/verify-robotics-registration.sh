[ "$WHEEL_COUNT" -eq 1 ] || die "expected exactly one built wheel, found $WHEEL_COUNT in $WHEELHOUSE"
WHEEL_NAME="$(basename -- "$WHEEL_PATH")"
[ "$WHEEL_NAME" = "flyto_modules_robotics-0.1.1-py3-none-any.whl" ] \
    || die "built wheel is not flyto_modules_robotics-0.1.1-py3-none-any.whl, got: $WHEEL_NAME"
