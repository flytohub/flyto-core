def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        while True:
            chunk = handle.read(1024 * 1024)
            if not chunk:
                break
            digest.update(chunk)
    return digest.hexdigest()


def read_regular_file(label, path, contained_in, inv):
    """Read a file only if it is an unremarkable, contained, regular file."""
    if not isinstance(path, str) or not os.path.isabs(path):
        fail("%s path is not an absolute path: %r" % (label, path), inv)
        return None
    normalised = os.path.normpath(path)
    if normalised != path:
        fail("%s path is not normalised: %s" % (label, path), inv)
        return None
    root = os.path.normpath(contained_in)
    if not (normalised == root or normalised.startswith(root + os.sep)):
        fail("%s path escapes %s: %s" % (label, root, path), inv)
        return None
    try:
        info = os.lstat(normalised)
    except OSError as exc:
        fail("%s is unreachable: %s (%s)" % (label, path, exc), inv)
        return None
    if stat.S_ISLNK(info.st_mode):
        fail("%s is a symlink, which this verifier refuses: %s" % (label, path),
             "evidence_files_are_regular_and_not_symlinks")
        return None
    if not stat.S_ISREG(info.st_mode):
        fail("%s is not a regular file: %s" % (label, path),
             "evidence_files_are_regular_and_not_symlinks")
        return None
    if os.path.realpath(normalised) != normalised:
        fail("%s resolves through a symlink: %s -> %s"
             % (label, path, os.path.realpath(normalised)),
             "evidence_files_are_regular_and_not_symlinks")
        return None
    try:
        with open(normalised, "rb") as handle:
            data = handle.read()
    except OSError as exc:
        fail("%s cannot be read: %s (%s)" % (label, path, exc), inv)
        return None
    return {
        "path": normalised,
        "bytes": data,
        "sha256": sha256_bytes(data),
        "mtime": info.st_mtime,
        "size": info.st_size,
    }


def parse_json(label, data, inv):
    try:
        return json.loads(data.decode("utf-8"))
    except Exception as exc:
        fail("%s is not valid UTF-8 JSON: %s" % (label, exc), inv)
        return None


def parse_utc(label, text, inv):
    if not isinstance(text, str):
        fail("%s is not a string timestamp: %r" % (label, text), inv)
        return None
    raw = text.strip()
    if not raw.endswith("Z"):
        fail("%s is not an explicit UTC timestamp ending in Z: %r" % (label, text), inv)
        return None
    for pattern in ("%Y-%m-%dT%H:%M:%SZ", "%Y-%m-%dT%H:%M:%S.%fZ"):
        try:
            parsed = _dt.datetime.strptime(raw, pattern)
        except ValueError:
            continue
        return parsed.replace(tzinfo=_dt.timezone.utc)
    fail("%s is not an ISO-8601 UTC timestamp: %r" % (label, text), inv)
    return None


def walk(node, path="$"):
    yield path, node
    if isinstance(node, dict):
        for key in node:
            for item in walk(node[key], "%s.%s" % (path, key)):
                yield item
    elif isinstance(node, list):
        for index, value in enumerate(node):
            for item in walk(value, "%s[%d]" % (path, index)):
                yield item


def find_contract_objects(node, contract):
    return [(path, value) for path, value in walk(node)
            if isinstance(value, dict) and value.get("contract_version") == contract]


def find_key(node, key):
    found = []
    for path, value in walk(node):
        if isinstance(value, dict) and key in value:
            found.append(("%s.%s" % (path, key), value[key]))
    return found


