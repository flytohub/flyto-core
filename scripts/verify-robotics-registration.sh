failures = []
invariant_failures = {}


def fail(message, inv=None):
    failures.append(message)
    if inv is not None:
        invariant_failures.setdefault(inv, []).append(message)


def require(condition, message, inv=None):
    if not condition:
        fail(message, inv)
    return bool(condition)


def require_exact(label, actual, expected, inv=None):
    if actual != expected or type(actual) is not type(expected):
        fail("%s: expected %r (%s), got %r (%s)"
             % (label, expected, type(expected).__name__,
                actual, type(actual).__name__), inv)
        return False
    return True


def require_true(label, value, inv=None):
    if value is not True:
        fail("%s: expected the boolean True, got %r" % (label, value), inv)
        return False
    return True


def require_false(label, value, inv=None):
    if value is not False:
        fail("%s: expected the boolean False, got %r" % (label, value), inv)
        return False
    return True


# ------------------------------------------------------------------------------
# Non-actuation guards
# ------------------------------------------------------------------------------
class NonActuatingViolation(RuntimeError):
    """Raised when verified code tries to act on the world."""


def install_non_actuation_guards():
    """Make shelling out and reaching the network impossible, not merely unwise."""
    def blocked(what):
        def _blocked(*_args, **_kwargs):
            raise NonActuatingViolation(
                "%s is forbidden inside the Core robotics registration verifier" % what
            )
        return _blocked

    import subprocess  # imported solely so its callables can be disabled
    for name in ("Popen", "run", "call", "check_call", "check_output",
                 "getoutput", "getstatusoutput"):
        if hasattr(subprocess, name):
            setattr(subprocess, name, blocked("subprocess.%s" % name))

    for name in ("system", "popen", "execv", "execve", "execvp", "execvpe",
                 "spawnv", "spawnve", "spawnvp", "spawnvpe", "posix_spawn",
                 "posix_spawnp", "fork", "forkpty"):
        if hasattr(os, name):
            setattr(os, name, blocked("os.%s" % name))

    # Sockets are blocked at connection and resolution, not construction:
    # asyncio builds its own AF_UNIX self-pipe with socketpair() and must keep
    # working. What matters is that nothing can reach off this machine.
    import socket
    for name in ("create_connection", "create_server", "getaddrinfo",
                 "gethostbyname", "gethostbyname_ex", "gethostbyaddr"):
        if hasattr(socket, name):
            setattr(socket, name, blocked("socket.%s" % name))
    for name in ("connect", "connect_ex", "sendto"):
        if hasattr(socket.socket, name):
            setattr(socket.socket, name, blocked("socket.socket.%s" % name))


