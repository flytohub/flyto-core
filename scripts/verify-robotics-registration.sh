    || die "failed to copy the modules source tree into scratch"

[ -f "$BUILD_SRC/pyproject.toml" ] || die "scratch source copy is missing pyproject.toml"

BUILD_COMMAND="python -m build --wheel --no-isolation --outdir <scratch>/wheelhouse <scratch>/source"
note "building exactly one wheel with $PYTHON_BIN ($PYTHON_VERSION)"
if ! "$PYTHON_BIN" -m build --wheel --no-isolation --outdir "$WHEELHOUSE" "$BUILD_SRC" \
        >"$SCRATCH/build.log" 2>&1; then
