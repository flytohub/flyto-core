note "copying flyto-modules-robotics source into scratch (the repository is never written to)"
(
    cd -P -- "$MODULES_REPO" && tar -cf - \
        --exclude './results' \
        --exclude './.git' \
        --exclude './build' \
        --exclude './dist' \
        --exclude './.venv' \
