# flyto.robotics.plan.v1 is not this verifier's contract to define.
#
# An earlier revision embedded a hand-written subset of the plan schema here.
# It "validated" plans against what Core happened to expect and rejected
# canonical fields - goal, generated_by, step_id, timeout_seconds, on_failure -
# that the real contract requires. A schema invented by the checker proves
# nothing about the contract; it only proves the checker agrees with itself.
#
# The canonical schema is read from the lower repository the evidence itself
# points at, hashed, sanity-checked, and then applied verbatim.
# ------------------------------------------------------------------------------
PLAN_SCHEMA_RELPATH = os.path.join("contracts", "plan-v1.schema.json")

# Keywords this validator implements and enforces.
_ASSERTION_KEYWORDS = frozenset([
    "$ref",
    "type", "enum", "const",
    "properties", "required", "additionalProperties", "patternProperties",
    "propertyNames", "minProperties", "maxProperties",
    "dependentRequired", "dependentSchemas", "dependencies",
    "items", "prefixItems", "additionalItems", "contains",
    "minItems", "maxItems", "uniqueItems",
    "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "multipleOf",
    "minLength", "maxLength", "pattern",
    "allOf", "anyOf", "oneOf", "not", "if", "then", "else",
])

# Keywords that annotate rather than constrain. Ignoring these is correct;
# anything outside both sets is refused, so the validator can never quietly
# under-check a contract it does not fully implement.
_ANNOTATION_KEYWORDS = frozenset([
    "$schema", "$id", "id", "$anchor", "$comment", "$defs", "definitions",
    "title", "description", "default", "examples", "deprecated",
    "readOnly", "writeOnly", "format", "contentMediaType", "contentEncoding",
])


class SchemaError(Exception):
    """The contract schema itself is malformed or beyond this validator."""


def _resolve_ref(ref, root):
    if not isinstance(ref, str) or not ref.startswith("#"):
        raise SchemaError("only local JSON pointers are supported, got %r" % (ref,))
    pointer = ref[1:]
    node = root
    if pointer in ("", "/"):
        return node
    for raw in pointer.lstrip("/").split("/"):
        token = raw.replace("~1", "/").replace("~0", "~")
        if isinstance(node, dict):
            if token not in node:
                raise SchemaError("unresolvable JSON pointer %r" % (ref,))
            node = node[token]
        elif isinstance(node, list):
            try:
                node = node[int(token)]
            except (ValueError, IndexError):
                raise SchemaError("unresolvable JSON pointer %r" % (ref,))
        else:
            raise SchemaError("unresolvable JSON pointer %r" % (ref,))
    return node


def _deref(schema, root, depth=0):
    while isinstance(schema, dict) and "$ref" in schema and depth < 32:
        schema = _resolve_ref(schema["$ref"], root)
        depth += 1
    return schema


def _type_matches(instance, name):
    if name == "null":
        return instance is None
    if name == "boolean":
        return isinstance(instance, bool)
    if name == "integer":
        return isinstance(instance, int) and not isinstance(instance, bool)
    if name == "number":
        return isinstance(instance, (int, float)) and not isinstance(instance, bool)
    if name == "string":
        return isinstance(instance, str)
    if name == "array":
        return isinstance(instance, list)
    if name == "object":
        return isinstance(instance, dict)
    raise SchemaError("unknown JSON Schema type %r" % (name,))


def _json_equal(left, right):
    # JSON equality, except that True == 1 must not hold.
    if isinstance(left, bool) != isinstance(right, bool):
        return False
    if isinstance(left, dict) and isinstance(right, dict):
        return (set(left) == set(right)
                and all(_json_equal(left[key], right[key]) for key in left))
    if isinstance(left, list) and isinstance(right, list):
        return (len(left) == len(right)
                and all(_json_equal(a, b) for a, b in zip(left, right)))
    return left == right


def validate_schema(instance, schema, root=None, path="$", errors=None):
    """Validate `instance` against `schema`, collecting every violation.

    Supports the draft-07 / 2020-12 assertion vocabulary listed above. Any
    keyword outside the known assertion and annotation sets raises SchemaError
    rather than being skipped: a contract this verifier cannot fully enforce
    must stop the run, not silently pass it.
    """
    if errors is None:
        errors = []
    if root is None:
        root = schema
    if schema is True:
        return errors
    if schema is False:
        errors.append("%s: schema permits no value here" % path)
        return errors
    if not isinstance(schema, dict):
        raise SchemaError("%s: schema fragment is not an object or boolean" % path)

    for keyword in schema:
        if keyword not in _ASSERTION_KEYWORDS and keyword not in _ANNOTATION_KEYWORDS:
            raise SchemaError(
                "%s: unsupported JSON Schema keyword %r; this verifier refuses to "
                "under-validate a contract it does not fully implement" % (path, keyword))

    if "$ref" in schema:
        validate_schema(instance, _resolve_ref(schema["$ref"], root), root, path, errors)

    # ---- any instance -------------------------------------------------------
    if "type" in schema:
        names = schema["type"]
        names = names if isinstance(names, list) else [names]
        if not any(_type_matches(instance, name) for name in names):
            errors.append("%s: expected type %s, got %s"
                          % (path, "/".join(names), type(instance).__name__))
            return errors
    if "const" in schema and not _json_equal(instance, schema["const"]):
        errors.append("%s: expected constant %r, got %r" % (path, schema["const"], instance))
    if "enum" in schema and not any(_json_equal(instance, value) for value in schema["enum"]):
        errors.append("%s: %r is not one of %r" % (path, instance, schema["enum"]))

    for keyword, combine in (("allOf", "all"), ("anyOf", "any"), ("oneOf", "one")):
        if keyword not in schema:
            continue
        branches = schema[keyword]
        outcomes = []
        for index, branch in enumerate(branches):
            branch_errors = validate_schema(
                instance, branch, root, "%s/%s[%d]" % (path, keyword, index), [])
            outcomes.append(branch_errors)
        matched = sum(1 for branch_errors in outcomes if not branch_errors)
        if combine == "all":
            for branch_errors in outcomes:
                errors.extend(branch_errors)
        elif combine == "any" and matched == 0:
            errors.append("%s: matched none of the %d anyOf branches" % (path, len(branches)))
        elif combine == "one" and matched != 1:
            errors.append("%s: matched %d oneOf branches, expected exactly 1"
                          % (path, matched))
    if "not" in schema:
        if not validate_schema(instance, schema["not"], root, "%s/not" % path, []):
            errors.append("%s: matched a schema it must not match" % path)
    if "if" in schema:
        condition_met = not validate_schema(instance, schema["if"], root, "%s/if" % path, [])
        branch = "then" if condition_met else "else"
        if branch in schema:
            validate_schema(instance, schema[branch], root, "%s/%s" % (path, branch), errors)

    # ---- strings ------------------------------------------------------------
    if isinstance(instance, str):
        if "minLength" in schema and len(instance) < schema["minLength"]:
            errors.append("%s: shorter than minLength %d" % (path, schema["minLength"]))
        if "maxLength" in schema and len(instance) > schema["maxLength"]:
            errors.append("%s: longer than maxLength %d" % (path, schema["maxLength"]))
        if "pattern" in schema:
            import re as _re
            if _re.search(schema["pattern"], instance) is None:
                errors.append("%s: %r does not match pattern %r"
                              % (path, instance, schema["pattern"]))

    # ---- numbers ------------------------------------------------------------
    if isinstance(instance, (int, float)) and not isinstance(instance, bool):
        if "minimum" in schema and instance < schema["minimum"]:
            errors.append("%s: %r is below minimum %r" % (path, instance, schema["minimum"]))
        if "maximum" in schema and instance > schema["maximum"]:
            errors.append("%s: %r is above maximum %r" % (path, instance, schema["maximum"]))
        if "exclusiveMinimum" in schema and instance <= schema["exclusiveMinimum"]:
            errors.append("%s: %r is not above exclusiveMinimum %r"
                          % (path, instance, schema["exclusiveMinimum"]))
        if "exclusiveMaximum" in schema and instance >= schema["exclusiveMaximum"]:
            errors.append("%s: %r is not below exclusiveMaximum %r"
                          % (path, instance, schema["exclusiveMaximum"]))
        if "multipleOf" in schema:
            divisor = schema["multipleOf"]
            if divisor <= 0 or (instance % divisor) != 0:
                errors.append("%s: %r is not a multiple of %r" % (path, instance, divisor))

    # ---- objects ------------------------------------------------------------
    if isinstance(instance, dict):
        properties = schema.get("properties", {})
        pattern_properties = schema.get("patternProperties", {})
        for key in schema.get("required", []):
            if key not in instance:
                errors.append("%s: missing required property %r" % (path, key))
        if "minProperties" in schema and len(instance) < schema["minProperties"]:
            errors.append("%s: fewer than minProperties %d" % (path, schema["minProperties"]))
        if "maxProperties" in schema and len(instance) > schema["maxProperties"]:
            errors.append("%s: more than maxProperties %d" % (path, schema["maxProperties"]))
        for key in sorted(properties):
            if key in instance:
                validate_schema(instance[key], properties[key], root,
                                "%s.%s" % (path, key), errors)
        if pattern_properties:
            import re as _re
            for expression in sorted(pattern_properties):
                for key in sorted(instance):
                    if _re.search(expression, key) is not None:
                        validate_schema(instance[key], pattern_properties[expression], root,
                                        "%s.%s" % (path, key), errors)
        if "additionalProperties" in schema:
            import re as _re
            extra = schema["additionalProperties"]
            for key in sorted(instance):
                if key in properties:
                    continue
                if any(_re.search(expression, key) is not None
                       for expression in pattern_properties):
                    continue
                if extra is False:
                    errors.append(
                        "%s: unexpected property %r (additionalProperties is false)"
                        % (path, key))
                else:
                    validate_schema(instance[key], extra, root,
                                    "%s.%s" % (path, key), errors)
        if "propertyNames" in schema:
            for key in sorted(instance):
                validate_schema(key, schema["propertyNames"], root,
                                "%s/propertyNames.%s" % (path, key), errors)
        for keyword in ("dependentRequired", "dependencies", "dependentSchemas"):
            for key, dependency in sorted(schema.get(keyword, {}).items()):
                if key not in instance:
                    continue
                if isinstance(dependency, list):
                    for needed in dependency:
                        if needed not in instance:
                            errors.append("%s: property %r requires %r"
                                          % (path, key, needed))
                else:
                    validate_schema(instance, dependency, root,
                                    "%s/%s[%s]" % (path, keyword, key), errors)

    # ---- arrays -------------------------------------------------------------
    if isinstance(instance, list):
        if "minItems" in schema and len(instance) < schema["minItems"]:
            errors.append("%s: expected at least %d item(s), got %d"
                          % (path, schema["minItems"], len(instance)))
        if "maxItems" in schema and len(instance) > schema["maxItems"]:
            errors.append("%s: expected at most %d item(s), got %d"
                          % (path, schema["maxItems"], len(instance)))
        if schema.get("uniqueItems") is True:
            for i in range(len(instance)):
                for j in range(i + 1, len(instance)):
                    if _json_equal(instance[i], instance[j]):
                        errors.append("%s: items %d and %d are duplicates" % (path, i, j))
        prefix = schema.get("prefixItems")
        offset = 0
        if prefix is not None:
            for index, subschema in enumerate(prefix):
                if index < len(instance):
                    validate_schema(instance[index], subschema, root,
                                    "%s[%d]" % (path, index), errors)
            offset = len(prefix)
        item_schema = schema.get("items")
        if isinstance(item_schema, list):
            # draft-07 tuple form
            for index, subschema in enumerate(item_schema):
                if index < len(instance):
                    validate_schema(instance[index], subschema, root,
                                    "%s[%d]" % (path, index), errors)
            offset = len(item_schema)
            extra_items = schema.get("additionalItems")
            if extra_items is not None:
                for index in range(offset, len(instance)):
                    if extra_items is False:
                        errors.append("%s[%d]: additionalItems is false" % (path, index))
                    else:
                        validate_schema(instance[index], extra_items, root,
                                        "%s[%d]" % (path, index), errors)
        elif item_schema is not None:
            for index in range(offset, len(instance)):
                validate_schema(instance[index], item_schema, root,
                                "%s[%d]" % (path, index), errors)
        if "contains" in schema:
            if not any(not validate_schema(item, schema["contains"], root, path, [])
                       for item in instance):
                errors.append("%s: no item satisfies `contains`" % path)
    return errors


def load_plan_contract(lower_repo, inv):
    """Read, hash and sanity-check the canonical flyto.robotics.plan.v1 schema.

    The schema is trusted to define the contract, but not blindly: it must still
    be the closed, capability-requiring shape this closure depends on, and it
    must not have grown a module_id requirement, which plan v1 does not have.
    """
    path = os.path.join(lower_repo, PLAN_SCHEMA_RELPATH)
    entry = read_regular_file("plan v1 contract schema", path, lower_repo, inv)
    if entry is None:
        return None, None
    schema = parse_json("plan v1 contract schema", entry["bytes"], inv)
    if not isinstance(schema, dict):
        fail("plan v1 contract schema is not a JSON object: %s" % path, inv)
        return None, {"path": entry["path"], "sha256": entry["sha256"],
                      "size_bytes": entry["size"], "usable": False}

    try:
        plan_schema = _deref(schema, schema)
        if not isinstance(plan_schema, dict):
            raise SchemaError("the plan schema root is not an object")
        plan_properties = plan_schema.get("properties", {})
        plan_properties = plan_properties if isinstance(plan_properties, dict) else {}
        steps_schema = _deref(plan_properties.get("steps", {}), schema)
        steps_schema = steps_schema if isinstance(steps_schema, dict) else {}
        # A tuple-form `items` would mean plan steps are positional, which plan v1
        # is not; leave step_schema empty so the shape checks below say so aloud.
        step_schema = _deref(steps_schema.get("items", {}), schema)
        step_schema = step_schema if isinstance(step_schema, dict) else {}
    except SchemaError as exc:
        fail("plan v1 contract schema cannot be resolved: %s" % exc, inv)
        return None, {"path": entry["path"], "sha256": entry["sha256"],
                      "size_bytes": entry["size"], "usable": False}

    plan_required = list(plan_schema.get("required", []) or [])
    step_required = list(step_schema.get("required", []) or [])

    require(plan_schema.get("additionalProperties") is False,
            "plan v1 contract schema does not close additionalProperties on the plan "
            "object", inv)
    require(step_schema.get("additionalProperties") is False,
            "plan v1 contract schema does not close additionalProperties on a plan step",
            inv)
    require("capability" in step_required,
            "plan v1 contract schema does not require `capability` on a plan step", inv)
    require("module_id" not in plan_required and "module_id" not in step_required,
            "plan v1 contract schema requires module_id; plan v1 has no such field and "
            "this verifier will not adopt an invented one", inv)

    pinned = plan_properties.get("contract_version")
    if isinstance(pinned, dict):
        if "const" in pinned:
            require_exact("plan v1 contract schema contract_version const",
                          pinned["const"], PLAN_CONTRACT, inv)
        elif "enum" in pinned:
            require_exact("plan v1 contract schema contract_version enum",
                          list(pinned["enum"]), [PLAN_CONTRACT], inv)

    return schema, {
        "path": entry["path"],
        "sha256": entry["sha256"],
        "size_bytes": entry["size"],
        "source_repository": lower_repo,
        "plan_required": sorted(plan_required),
        "plan_additional_properties_closed": plan_schema.get("additionalProperties") is False,
        "step_required": sorted(step_required),
        "step_additional_properties_closed": step_schema.get("additionalProperties") is False,
        "plan_properties": sorted(plan_properties),
        "step_properties": sorted(step_schema.get("properties", {}) or {}),
        "requires_module_id": "module_id" in plan_required or "module_id" in step_required,
    }


