#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# verify-robotics-registration.sh
#
# Strict, local, NON-ACTUATING Core-side verifier for one already-finished
# flyto-modules-robotics Gazebo evidence run.
#
# What this script proves:
#
#   1. One finished flyto-modules-robotics Gazebo evidence run is internally
#      consistent, fresh, hash-intact, and carries the contract versions, pass
#      facts, restoration facts, zero-command facts and final-status facts its
#      own contracts promise.
#   2. The flyto-modules-robotics source in the derived repository builds
#      exactly one wheel, and that wheel - installed offline into a throwaway
#      target - registers into *this* flyto-core checkout through the real
#      public ModuleRegistry plugin surface as the `robotics` entry point.
#   3. The three robotics modules produce declaration-only plans: nothing is
#      dispatched, every plan satisfies flyto.robotics.plan.v1 and ends in
#      `safe_stop`, and every plan is bound to a synthetic device id that
#      exists only inside this verification.
#
# What this script does NOT prove and does NOT do:
#
#   * It is NOT physical-hardware evidence. Every physical fact it reports is
#     restated from a Gazebo simulation run that happened earlier, elsewhere.
#   * It never contacts hardware, never starts ROS / Gazebo / Lima, never
#     connects a socket, never logs in, never dispatches a plan, and never
#     publishes cmd_vel. The embedded verifier disables subprocess execution
#     and outbound networking inside its own interpreter, so "non-actuating"
#     is enforced rather than merely asserted.
#   * It never mutates the flyto-modules-robotics or flyto-robotics
#     repositories. The wheel is built from a scratch copy of the source tree,
#     and evidence files are only ever read.
#
# Usage:
#   scripts/verify-robotics-registration.sh <run-dir>
#   scripts/verify-robotics-registration.sh --run-dir <run-dir>
#   FLYTO_ROBOTICS_RUN_DIR=<run-dir> scripts/verify-robotics-registration.sh
#
# <run-dir> may also be the canonical run parent directory
# (<modules-repo>/results/modules-robotics-gazebo) or the modules repository
# root, but only when that location holds exactly one non-symlink run.
#
# Environment:
#   FLYTO_ROBOTICS_RUN_DIR        Run directory (lowest-precedence input).
#   FLYTO_VERIFY_PYTHON           Interpreter used to build, install and
#                                 verify. Defaults to python3. Must be 3.9+.
#   FLYTO_VERIFY_MAX_AGE_SECONDS  Explicit maximum evidence age in seconds.
#                                 Default 7200, hard upper bound 86400.
#
# Options:
#   --run-dir <dir>          Evidence run directory.
#   --max-age-seconds <n>    Explicit maximum evidence age (1..86400).
#   -h, --help               Show this help.
#
# Exit status is 0 only when every invariant holds.
# ==============================================================================

DEFAULT_MAX_AGE_SECONDS=7200
HARD_MAX_AGE_SECONDS=86400
RUN_PARENT_NAME="modules-robotics-gazebo"
SCRATCH_PREFIX="flyto-robotics-verify"
readonly DEFAULT_MAX_AGE_SECONDS HARD_MAX_AGE_SECONDS RUN_PARENT_NAME SCRATCH_PREFIX

PROG="$(basename -- "$0")"

die() {
    printf '%s: error: %s\n' "$PROG" "$*" >&2
    exit 1
}

note() {
    printf '%s: %s\n' "$PROG" "$*" >&2
}

usage() {
    sed -n '4,60p' "$0" | sed -e 's/^#\{1,\} \{0,1\}//' -e 's/^#$//'
}

# ------------------------------------------------------------------------------
# Path hygiene
#
# Every path handed to the embedded verifier is embedded in a JSON config file
# generated by shell printf. Rather than build a general JSON escaper in bash
# 3.2, refuse the small set of characters that would make escaping necessary. A
# verification run is allowed to be picky about where it is asked to look.
# ------------------------------------------------------------------------------
assert_plain_path() {
    local label="$1" value="$2"
    case "$value" in
        '')     die "$label is empty" ;;
        *'"'*)  die "$label contains a double quote, which this verifier refuses: $value" ;;
        *'\'*)  die "$label contains a backslash, which this verifier refuses: $value" ;;
        *'$'*)  die "$label contains a dollar sign, which this verifier refuses: $value" ;;
        *'`'*)  die "$label contains a backtick, which this verifier refuses: $value" ;;
    esac
    case "$value" in
        /*) : ;;
        *)  die "$label is not absolute: $value" ;;
    esac
    if printf '%s' "$value" | LC_ALL=C tr -d '[:print:]' | LC_ALL=C grep -q .; then
        die "$label contains control characters, which this verifier refuses"
    fi
}

# Physical, symlink-free absolute path of an existing directory.
canonical_dir() {
    local d="$1"
    [ -d "$d" ] || die "not a directory: $d"
    (cd -P -- "$d" >/dev/null 2>&1 && pwd -P) || die "cannot canonicalise directory: $d"
}

# ------------------------------------------------------------------------------
# Argument parsing
# ------------------------------------------------------------------------------
RUN_DIR_ARG=""
MAX_AGE_ARG=""
MAX_AGE_SOURCE="default"

while [ "$#" -gt 0 ]; do
    case "$1" in
        -h|--help)
            usage
            exit 0
            ;;
        --run-dir)
            [ "$#" -ge 2 ] || die "--run-dir requires a value"
            [ -z "$RUN_DIR_ARG" ] || die "run directory given more than once"
            RUN_DIR_ARG="$2"
            shift 2
            ;;
        --run-dir=*)
            [ -z "$RUN_DIR_ARG" ] || die "run directory given more than once"
            RUN_DIR_ARG="${1#--run-dir=}"
            shift
            ;;
        --max-age-seconds)
            [ "$#" -ge 2 ] || die "--max-age-seconds requires a value"
            MAX_AGE_ARG="$2"
            MAX_AGE_SOURCE="--max-age-seconds"
            shift 2
            ;;
        --max-age-seconds=*)
            MAX_AGE_ARG="${1#--max-age-seconds=}"
            MAX_AGE_SOURCE="--max-age-seconds"
            shift
            ;;
        --)
            shift
            ;;
        -*)
            die "unknown option: $1 (try --help)"
            ;;
        *)
            [ -z "$RUN_DIR_ARG" ] || die "exactly one run directory may be given; got a second: $1"
            RUN_DIR_ARG="$1"
            shift
            ;;
    esac
done

if [ -z "$RUN_DIR_ARG" ]; then
    RUN_DIR_ARG="${FLYTO_ROBOTICS_RUN_DIR:-}"
    [ -n "$RUN_DIR_ARG" ] \
        || die "no run directory given (positional, --run-dir, or FLYTO_ROBOTICS_RUN_DIR); try --help"
fi

if [ -z "$MAX_AGE_ARG" ] && [ -n "${FLYTO_VERIFY_MAX_AGE_SECONDS:-}" ]; then
    MAX_AGE_ARG="$FLYTO_VERIFY_MAX_AGE_SECONDS"
    MAX_AGE_SOURCE="FLYTO_VERIFY_MAX_AGE_SECONDS"
fi

if [ -n "$MAX_AGE_ARG" ]; then
    case "$MAX_AGE_ARG" in
        ''|*[!0-9]*) die "maximum evidence age must be a positive integer number of seconds, got: $MAX_AGE_ARG" ;;
    esac
    MAX_AGE_SECONDS=$((10#$MAX_AGE_ARG))
    [ "$MAX_AGE_SECONDS" -ge 1 ] \
        || die "maximum evidence age must be at least 1 second"
    [ "$MAX_AGE_SECONDS" -le "$HARD_MAX_AGE_SECONDS" ] \
        || die "maximum evidence age $MAX_AGE_SECONDS exceeds the hard bound of $HARD_MAX_AGE_SECONDS seconds"
else
    MAX_AGE_SECONDS="$DEFAULT_MAX_AGE_SECONDS"
fi

# ------------------------------------------------------------------------------
# Locate this Core checkout
# ------------------------------------------------------------------------------
SCRIPT_DIR="$(canonical_dir "$(dirname -- "$0")")"
CORE_ROOT="$(canonical_dir "$SCRIPT_DIR/..")"
CORE_SRC="$CORE_ROOT/src"
[ -d "$CORE_SRC/core" ] || die "this does not look like a flyto-core checkout (missing $CORE_SRC/core)"
[ -f "$CORE_ROOT/pyproject.toml" ] || die "this does not look like a flyto-core checkout (missing pyproject.toml)"
assert_plain_path "core root" "$CORE_ROOT"

# ------------------------------------------------------------------------------
# Resolve the run directory
#
# A run directory is identified by the three artifacts the upper closure always
# writes. A parent directory or repository root is accepted only when it
# resolves, unambiguously, to exactly one non-symlink run.
# ------------------------------------------------------------------------------
looks_like_run_dir() {
    [ -f "$1/report.json" ] && [ -f "$1/cleanup.json" ] && [ -f "$1/lower-evidence.json" ]
}

sole_run_in_parent() {
    local parent="$1"
    local candidate="" entry="" count=0 had_nullglob=0
    if shopt -q nullglob; then had_nullglob=1; else shopt -s nullglob; fi
    for entry in "$parent"/*; do
        [ -d "$entry" ] || continue
        if [ -L "$entry" ]; then
            note "ignoring symlinked entry while resolving the sole run: $entry"
            continue
        fi
        looks_like_run_dir "$entry" || continue
        candidate="$entry"
        count=$((count + 1))
    done
    [ "$had_nullglob" -eq 1 ] || shopt -u nullglob
    if [ "$count" -eq 0 ]; then
        die "no evidence run found under $parent"
    fi
    if [ "$count" -gt 1 ]; then
        die "$parent holds $count runs; this verifier takes exactly one run directory, name it explicitly"
    fi
    printf '%s\n' "$candidate"
}

[ -e "$RUN_DIR_ARG" ] || die "run directory does not exist: $RUN_DIR_ARG"
if [ -L "$RUN_DIR_ARG" ]; then
    die "run directory is a symlink, which this verifier refuses: $RUN_DIR_ARG"
fi
[ -d "$RUN_DIR_ARG" ] || die "run directory is not a directory: $RUN_DIR_ARG"

RESOLVED_INPUT="$(canonical_dir "$RUN_DIR_ARG")"
RUN_DIR_INPUT_KIND="run directory"

if looks_like_run_dir "$RESOLVED_INPUT"; then
    RUN_DIR="$RESOLVED_INPUT"
elif [ "$(basename -- "$RESOLVED_INPUT")" = "$RUN_PARENT_NAME" ]; then
    RUN_DIR_INPUT_KIND="canonical run parent"
    RUN_DIR="$(sole_run_in_parent "$RESOLVED_INPUT")"
elif [ -d "$RESOLVED_INPUT/results/$RUN_PARENT_NAME" ]; then
    RUN_DIR_INPUT_KIND="modules repository root"
    RUN_DIR="$(sole_run_in_parent "$(canonical_dir "$RESOLVED_INPUT/results/$RUN_PARENT_NAME")")"
else
    die "not an evidence run directory, canonical run parent, or modules repository root: $RESOLVED_INPUT"
fi

RUN_DIR="$(canonical_dir "$RUN_DIR")"
looks_like_run_dir "$RUN_DIR" || die "resolved run directory is missing required artifacts: $RUN_DIR"
assert_plain_path "run directory" "$RUN_DIR"

RUN_ID="$(basename -- "$RUN_DIR")"

# ------------------------------------------------------------------------------
# Derive the modules repository from the run directory layout
# ------------------------------------------------------------------------------
RUN_PARENT="$(canonical_dir "$RUN_DIR/..")"
[ "$(basename -- "$RUN_PARENT")" = "$RUN_PARENT_NAME" ] \
    || die "run directory is not under results/$RUN_PARENT_NAME: $RUN_DIR"
RESULTS_DIR="$(canonical_dir "$RUN_PARENT/..")"
[ "$(basename -- "$RESULTS_DIR")" = "results" ] \
    || die "run parent is not under a results/ directory: $RUN_PARENT"
MODULES_REPO="$(canonical_dir "$RESULTS_DIR/..")"
[ -f "$MODULES_REPO/pyproject.toml" ] \
    || die "derived modules repository has no pyproject.toml: $MODULES_REPO"
assert_plain_path "modules repository" "$MODULES_REPO"

if ! LC_ALL=C grep -q '^[[:space:]]*name[[:space:]]*=[[:space:]]*["'"'"']flyto-modules-robotics["'"'"']' \
        "$MODULES_REPO/pyproject.toml"; then
    die "derived repository does not declare the flyto-modules-robotics project: $MODULES_REPO/pyproject.toml"
fi

if [ "$MODULES_REPO" = "$CORE_ROOT" ]; then
    die "the derived modules repository is this Core checkout; refusing"
fi

# ------------------------------------------------------------------------------
# Interpreter selection
# ------------------------------------------------------------------------------
PYTHON_BIN="${FLYTO_VERIFY_PYTHON:-python3}"
case "$PYTHON_BIN" in
    /*) : ;;
    *)
        RESOLVED_PYTHON="$(command -v -- "$PYTHON_BIN" 2>/dev/null || true)"
        [ -n "$RESOLVED_PYTHON" ] || die "interpreter not found on PATH: $PYTHON_BIN"
        PYTHON_BIN="$RESOLVED_PYTHON"
        ;;
esac
[ -x "$PYTHON_BIN" ] || die "interpreter is not executable: $PYTHON_BIN"
assert_plain_path "interpreter" "$PYTHON_BIN"

PYTHON_VERSION="$("$PYTHON_BIN" -c 'import sys; print("%d.%d.%d" % sys.version_info[:3])')" \
    || die "cannot run the selected interpreter: $PYTHON_BIN"
"$PYTHON_BIN" -c 'import sys; raise SystemExit(0 if sys.version_info[:2] >= (3, 9) else 1)' \
    || die "interpreter must be Python 3.9 or newer, got $PYTHON_VERSION from $PYTHON_BIN"

# Build and install are the only stages permitted to run tooling. Keep them
# hermetic: no user site, no network index, no build isolation.
export PYTHONNOUSERSITE=1
export PIP_DISABLE_PIP_VERSION_CHECK=1
export PIP_NO_INPUT=1
unset PYTHONPATH 2>/dev/null || true

# ------------------------------------------------------------------------------
# Scratch space
# ------------------------------------------------------------------------------
TMPROOT="${TMPDIR:-/tmp}"
case "$TMPROOT" in
    */) TMPROOT="${TMPROOT%/}" ;;
esac
[ -d "$TMPROOT" ] || TMPROOT="/tmp"
TMPROOT="$(canonical_dir "$TMPROOT")"

SCRATCH="$(mktemp -d "$TMPROOT/$SCRATCH_PREFIX.XXXXXXXX")" || die "cannot create scratch directory"
SCRATCH="$(canonical_dir "$SCRATCH")"
assert_plain_path "scratch directory" "$SCRATCH"

cleanup_scratch() {
    # Narrow by construction: only ever remove a real directory this run
    # created, under the temporary root, whose basename carries this
    # verifier's prefix and mktemp suffix.
    if [ -n "${SCRATCH:-}" ] && [ -d "$SCRATCH" ] && [ ! -L "$SCRATCH" ]; then
        case "$(basename -- "$SCRATCH")" in
            "$SCRATCH_PREFIX".????????)
                case "$SCRATCH" in
                    "$TMPROOT"/*) rm -rf -- "$SCRATCH" ;;
                esac
                ;;
        esac
    fi
}
trap 'cleanup_scratch' EXIT
trap 'trap - EXIT; cleanup_scratch; exit 130' INT
trap 'trap - EXIT; cleanup_scratch; exit 143' TERM

BUILD_SRC="$SCRATCH/source"
WHEELHOUSE="$SCRATCH/wheelhouse"
TARGET="$SCRATCH/target"
mkdir -p -- "$BUILD_SRC" "$WHEELHOUSE" "$TARGET"

# ------------------------------------------------------------------------------
# Copy the modules source into scratch, then build there.
#
# `--no-isolation` builds in place, and building in place would leave build/,
# dist/ and *.egg-info behind in a repository this closure does not own. Copy
# first; the source repository stays byte-identical.
