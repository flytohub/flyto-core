            "max_evidence_age_seconds": cfg["max_age_seconds"],
            "max_evidence_age_source": cfg["max_age_source"],
            "default_max_evidence_age_seconds": cfg["default_max_age_seconds"],
            "hard_max_evidence_age_seconds": cfg["hard_max_age_seconds"],
