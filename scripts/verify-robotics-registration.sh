        },
        "provenance": {
            "verifier": "scripts/verify-robotics-registration.sh",
            "core_root": cfg["core_root"],
            "core_src": cfg["core_src"],
            "python_executable": cfg["python_executable"],
            "python_version": cfg["python_version"],
            "scratch_root": cfg["scratch"],
            "result_dir": cfg["result_dir"],
            "evidence_provenance": state.get("evidence_provenance", {}),
        },
        "input": state.get("input", {}),
        "evidence": {
            "source_hashes": state.get("source_hashes", {}),
            "copies": state.get("copies", {}),
            "evidence_dir": os.path.join(cfg["result_dir"], "evidence"),
        },
        "lower": state.get("lower", {}),
        "plan_contract": {
            "contract_version": PLAN_CONTRACT,
            "source": (
                "read from the derived lower repository, not defined by this verifier"),
            "relative_path": PLAN_SCHEMA_RELPATH,
            "schema": state.get("plan_contract"),
        },
        "wheel": {
            "filename": cfg["wheel_filename"],
            "version": DISTRIBUTION_VERSION,
            "sha256": (sha256_file(wheel_path) if os.path.isfile(wheel_path) else None),
            "path": wheel_path,
            "build_command": cfg["build_command"],
            "build_source": cfg["build_source"],
            "build_source_is_scratch_copy": True,
            "build_used_isolation": False,
            "source_repository_mutated": False,
            "install_command": cfg["install_command"],
            "install_target": cfg["target"],
            "install_offline_no_index": True,
            "install_no_deps": True,
        },
        "import_origins": state.get("import_origins", {}),
        "registration": state.get("registration", {}),
        "device_binding": {
            "synthetic_device_id": DEVICE_ID,
            "context": dict(CONTEXT),
            "binding_is_synthetic": True,
            "no_real_resource_was_reserved": True,
            "resource_id_source": "invented by this verifier; it names no real robot",
        },
        "executions": state.get("executions", {}),
        "discovery_errors": state.get("discovery_errors", []),
        "failures": list(failures),
    }

    report["invariants"] = {
        key: (key not in invariant_failures) for key in INVARIANTS
    }
    report["invariant_failures"] = {
        key: list(messages) for key, messages in sorted(invariant_failures.items())
    }
    # An unattributed failure still invalidates the run, even when every named
    # invariant survived it. Say so instead of letting the table imply success.
    report["unattributed_failures"] = [
        message for message in failures
        if not any(message in messages for messages in invariant_failures.values())
    ]

    report_path = os.path.join(cfg["result_dir"], "report.json")
    report_sha = write_atomic_json(report_path, report)

    sys.stdout.write("report_path=%s\n" % report_path)
    sys.stdout.write("report_sha256=%s\n" % report_sha)
    sys.stdout.write("passed=%s\n" % ("true" if passed else "false"))
    if not passed:
        sys.stderr.write("\nrobotics registration verification FAILED:\n")
        for message in failures:
            sys.stderr.write("  - %s\n" % message)
    return 0 if passed else 1


# ==============================================================================
# Main
# ==============================================================================
def main(argv):
    if len(argv) != 2:
        sys.stderr.write("usage: verify_registration.py <config.json>\n")
        return 2

    with open(argv[1], "rb") as handle:
        cfg = json.loads(handle.read().decode("utf-8"))

    install_non_actuation_guards()

    started_at = _dt.datetime.now(_dt.timezone.utc)
    state = {}

    run_dir = cfg["run_dir"]
    run_id = cfg["run_id"]
    modules_repo = cfg["modules_repo"]
    target = os.path.realpath(cfg["target"])
    core_src = os.path.realpath(cfg["core_src"])
    result_dir = cfg["result_dir"]
    evidence_dir = os.path.join(result_dir, "evidence")
    max_age = cfg["max_age_seconds"]

    require(os.path.basename(run_dir) == run_id,
            "run directory basename %r does not match the run id %r"
            % (os.path.basename(run_dir), run_id),
            "run_dir_resolved_and_contained")
    require(run_dir.startswith(os.path.normpath(modules_repo) + os.sep),
            "run directory %s is not contained in the modules repository %s"
            % (run_dir, modules_repo),
            "run_dir_resolved_and_contained")
    require(os.path.realpath(result_dir).startswith(
                os.path.join(os.path.realpath(cfg["core_root"]),
                             "test-results", "robotics-registration") + os.sep),
            "result directory %s is not inside this Core checkout's "
            "test-results/robotics-registration" % result_dir,
            "run_dir_resolved_and_contained")

    # --------------------------------------------------------------------------
    # 1. Upper evidence
    # --------------------------------------------------------------------------
    upper_report_file = read_regular_file(
        "upper report", os.path.join(run_dir, "report.json"), run_dir,
        "upper_report_contract_and_pass_facts")
    upper_cleanup_file = read_regular_file(
        "upper cleanup", os.path.join(run_dir, "cleanup.json"), run_dir,
        "upper_cleanup_contract_run_id_and_final_status")
    lower_evidence_file = read_regular_file(
        "lower evidence", os.path.join(run_dir, "lower-evidence.json"), run_dir,
        "lower_evidence_equals_report_lower_layer")

    if not (upper_report_file and upper_cleanup_file and lower_evidence_file):
        return build_report(cfg, started_at, state)

    upper_report = parse_json("upper report", upper_report_file["bytes"],
                              "upper_report_contract_and_pass_facts")
    upper_cleanup = parse_json("upper cleanup", upper_cleanup_file["bytes"],
                               "upper_cleanup_contract_run_id_and_final_status")
    lower_evidence = parse_json("lower evidence", lower_evidence_file["bytes"],
                                "lower_evidence_equals_report_lower_layer")
    if not all(isinstance(doc, dict)
               for doc in (upper_report, upper_cleanup, lower_evidence)):
        fail("one or more evidence documents are not JSON objects")
        return build_report(cfg, started_at, state)

    inv_upper = "upper_report_contract_and_pass_facts"
    require_exact("upper report contract_version",
                  upper_report.get("contract_version"), UPPER_REPORT_CONTRACT, inv_upper)
    require_true("upper report passed", upper_report.get("passed"), inv_upper)
    require_exact("upper report run_id", upper_report.get("run_id"), run_id, inv_upper)

    provenance = upper_report.get("provenance")
    require(isinstance(provenance, dict), "upper report has no provenance object", inv_upper)
    provenance = provenance if isinstance(provenance, dict) else {}
    finished_at = parse_utc("upper report provenance.finished_at",
                            provenance.get("finished_at"),
                            "evidence_not_future_and_within_max_age")
    evidence_started_at = parse_utc("upper report provenance.started_at",
                                    provenance.get("started_at"),
                                    "evidence_not_future_and_within_max_age")
    if finished_at and evidence_started_at:
        require(evidence_started_at <= finished_at,
                "upper report provenance: started_at is after finished_at",
                "evidence_not_future_and_within_max_age")

    upper_invariants = upper_report.get("invariants")
    if require(isinstance(upper_invariants, dict),
               "upper report has no invariants object", inv_upper):
        for key in sorted(upper_invariants):
            require_true("upper report invariant %r" % key, upper_invariants[key], inv_upper)
        for needed in ("lower_layer_verified", "final_step_is_safe_stop",
                       "gateway_terminal_success", "gateway_did_not_time_out",
                       "physics_gate_satisfied", "displacement_in_window",
                       "stopped_pose_is_stable"):
            require(needed in upper_invariants,
                    "upper report invariants are missing %r" % needed, inv_upper)

    gateway = upper_report.get("gateway_session")
    if require(isinstance(gateway, dict), "upper report has no gateway_session", inv_upper):
        require_false("upper report gateway_session.timed_out",
                      gateway.get("timed_out"), inv_upper)
        require_exact("upper report gateway_session.error",
                      gateway.get("error"), None, inv_upper)
        terminal = gateway.get("terminal_success_states")
        require(isinstance(terminal, list) and gateway.get("state") in terminal,
                "upper report gateway_session.state %r is not a declared terminal "
                "success state" % (gateway.get("state"),), inv_upper)

    step = upper_report.get("step")
    if require(isinstance(step, dict), "upper report has no step object", inv_upper):
        require_exact("upper report step.final_step_capability",
                      step.get("final_step_capability"), SAFE_STOP, inv_upper)
        require_exact("upper report step.request_contract_version",
                      step.get("request_contract_version"), REQUEST_CONTRACT, inv_upper)
        require_exact("upper report step.plan_contract_version",
                      step.get("plan_contract_version"), PLAN_CONTRACT, inv_upper)

    inv_cleanup = "upper_cleanup_contract_run_id_and_final_status"
    inv_restore = "upper_restoration_and_quiescence_facts"
    require_exact("upper cleanup contract_version",
                  upper_cleanup.get("contract_version"), UPPER_CLEANUP_CONTRACT, inv_cleanup)
    require_exact("upper cleanup run_id", upper_cleanup.get("run_id"), run_id, inv_cleanup)
    require_exact("upper cleanup incoming_status",
                  upper_cleanup.get("incoming_status"), 0, inv_cleanup)
    require_exact("upper cleanup final_status",
                  upper_cleanup.get("final_status"), 0, inv_cleanup)
    require_true("upper cleanup restoration_attempted",
                 upper_cleanup.get("restoration_attempted"), inv_restore)
    require_exact("upper cleanup restoration_exit_code",
                  upper_cleanup.get("restoration_exit_code"), 0, inv_restore)
    require_false("upper cleanup restoration_timed_out",
                  upper_cleanup.get("restoration_timed_out"), inv_restore)
    require_true("upper cleanup restored_normal_gateway_runtime",
                 upper_cleanup.get("restored_normal_gateway_runtime"), inv_restore)
    require_true("upper cleanup lower_processes_quiesced",
                 upper_cleanup.get("lower_processes_quiesced"), inv_restore)
    require_true("upper cleanup guest_scratch_removed",
                 upper_cleanup.get("guest_scratch_removed"), inv_restore)

    # --------------------------------------------------------------------------
    # 2. lower-evidence.json is the report's own lower_layer, restated
    # --------------------------------------------------------------------------
    require("contract_version" not in lower_evidence,
            "lower-evidence.json carries a contract_version; by contract it must not",
            "lower_evidence_has_no_contract_version")

    lower_layer = upper_report.get("lower_layer")
    require(isinstance(lower_layer, dict), "upper report has no lower_layer object",
            "lower_evidence_equals_report_lower_layer")
    lower_layer = lower_layer if isinstance(lower_layer, dict) else {}
    require(lower_evidence == lower_layer,
            "lower-evidence.json is not exactly equal to the upper report's lower_layer",
            "lower_evidence_equals_report_lower_layer")

    inv_lower_report = "lower_report_contract_and_pass_facts"
    inv_lower_cleanup = "lower_cleanup_contract_zero_command_and_status"
    require_true("lower_layer.passed", lower_layer.get("passed"), inv_lower_report)
    require_true("lower_layer.report_passed", lower_layer.get("report_passed"),
                 inv_lower_report)
    require_exact("lower_layer.report_contract_version",
                  lower_layer.get("report_contract_version"),
                  LOWER_REPORT_CONTRACT, inv_lower_report)
    require_exact("lower_layer.cleanup_contract_version",
                  lower_layer.get("cleanup_contract_version"),
                  LOWER_CLEANUP_CONTRACT, inv_lower_cleanup)
    require_true("lower_layer.cleanup_has_no_run_id_field_by_contract",
                 lower_layer.get("cleanup_has_no_run_id_field_by_contract"),
                 inv_lower_cleanup)

    checked = lower_layer.get("cleanup_checked")
    if require(isinstance(checked, dict), "lower_layer has no cleanup_checked object",
               inv_lower_cleanup):
        require_true("lower_layer.cleanup_checked.passed", checked.get("passed"),
                     inv_lower_cleanup)
        require_true("lower_layer.cleanup_checked.restored_normal_gateway_runtime",
                     checked.get("restored_normal_gateway_runtime"), inv_lower_cleanup)
        require_true("lower_layer.cleanup_checked.zero_command_published",
                     checked.get("zero_command_published"), inv_lower_cleanup)
        require_exact("lower_layer.cleanup_checked.normal_runtime_restoration_exit_code",
                      checked.get("normal_runtime_restoration_exit_code"), 0,
                      inv_lower_cleanup)
        require_exact("lower_layer.cleanup_checked.verification_status",
                      checked.get("verification_status"), 0, inv_lower_cleanup)

    lower_run_id = lower_layer.get("lower_run_id")
    require_exact("upper cleanup lower_run_id", upper_cleanup.get("lower_run_id"),
                  lower_run_id, inv_cleanup)
    require(isinstance(lower_run_id, str) and lower_run_id == run_id + "-lower",
            "lower_run_id %r is not the upper run id with a -lower suffix"
            % (lower_run_id,), inv_cleanup)

    # --------------------------------------------------------------------------
    # 3. Lower evidence files, in the lower repository
    # --------------------------------------------------------------------------
    inv_paths = "lower_paths_contained_and_regular_files"
    inv_hashes = "declared_sha256_recomputed_and_matched"
    lower_run_dir = lower_layer.get("lower_run_dir")
    lower_report_path = lower_layer.get("report_path")
    lower_cleanup_path = lower_layer.get("cleanup_path")
    lower_repo = None
    lower_report_file = None
    lower_cleanup_file = None

    if not all(isinstance(value, str) and os.path.isabs(value)
               for value in (lower_run_dir, lower_report_path, lower_cleanup_path)):
        fail("lower_layer does not carry absolute lower_run_dir/report_path/cleanup_path",
             inv_paths)
    else:
        lower_run_dir = os.path.normpath(lower_run_dir)
        require(os.path.basename(lower_run_dir) == lower_run_id,
                "lower_run_dir basename %r does not match lower_run_id %r"
                % (os.path.basename(lower_run_dir), lower_run_id), inv_paths)
        parent = os.path.dirname(lower_run_dir)
        require(os.path.basename(parent) == LOWER_RESULTS_PARENT,
                "lower_run_dir is not under results/%s: %s"
                % (LOWER_RESULTS_PARENT, lower_run_dir), inv_paths)
        results_parent = os.path.dirname(parent)
        require(os.path.basename(results_parent) == "results",
                "lower_run_dir is not under a results/ directory: %s" % lower_run_dir,
                inv_paths)
        lower_repo = os.path.dirname(results_parent)
        require(lower_repo != os.path.normpath(modules_repo),
                "the lower repository and the modules repository are the same tree: %s"
                % lower_repo, inv_paths)
        require(os.path.isdir(lower_run_dir) and not os.path.islink(lower_run_dir),
                "lower run directory is missing or a symlink: %s" % lower_run_dir,
                inv_paths)
        lower_report_file = read_regular_file(
            "lower report", lower_report_path, lower_run_dir, inv_paths)
        lower_cleanup_file = read_regular_file(
            "lower cleanup", lower_cleanup_path, lower_run_dir, inv_paths)

    # The plan contract belongs to the lower repository, so it is only loadable
    # once the evidence has told us which repository that is.
    inv_contract = "plan_contract_schema_is_the_canonical_lower_contract"
    plan_schema = None
    plan_contract_facts = None
    if lower_repo is None:
        fail("the lower repository could not be derived, so the canonical %s schema "
             "could not be read" % PLAN_CONTRACT, inv_contract)
    else:
        plan_schema, plan_contract_facts = load_plan_contract(lower_repo, inv_contract)

    lower_report = None
    lower_cleanup = None
    if lower_report_file:
        require_exact("lower report sha256 (recomputed against the declared digest)",
                      lower_report_file["sha256"], lower_layer.get("report_sha256"),
                      inv_hashes)
        lower_report = parse_json("lower report", lower_report_file["bytes"],
                                  inv_lower_report)
    if lower_cleanup_file:
        require_exact("lower cleanup sha256 (recomputed against the declared digest)",
                      lower_cleanup_file["sha256"], lower_layer.get("cleanup_sha256"),
                      inv_hashes)
        lower_cleanup = parse_json("lower cleanup", lower_cleanup_file["bytes"],
                                   inv_lower_cleanup)

    if isinstance(lower_report, dict):
        require_exact("lower report contract_version",
                      lower_report.get("contract_version"), LOWER_REPORT_CONTRACT,
                      inv_lower_report)
        require_true("lower report passed", lower_report.get("passed"), inv_lower_report)
        robot = lower_report.get("robot")
        if require(isinstance(robot, dict), "lower report has no robot object",
                   inv_lower_report):
            require_true("lower report robot.passed", robot.get("passed"),
                         inv_lower_report)
            require_exact("lower report robot.contract_version",
                          robot.get("contract_version"), LOWER_REPORT_CONTRACT,
                          inv_lower_report)
        fault = lower_report.get("fault_safety")
        if require(isinstance(fault, dict), "lower report has no fault_safety object",
                   inv_lower_report):
            require_true("lower report fault_safety.passed", fault.get("passed"),
                         inv_lower_report)
            require_true("lower report fault_safety.safety_latched",
                         fault.get("safety_latched"), inv_lower_report)

    if isinstance(lower_cleanup, dict):
        require_exact("lower cleanup contract_version",
                      lower_cleanup.get("contract_version"), LOWER_CLEANUP_CONTRACT,
                      inv_lower_cleanup)
        require("run_id" not in lower_cleanup,
                "lower cleanup carries a run_id; the lower cleanup contract has none",
                inv_lower_cleanup)
        require_true("lower cleanup passed", lower_cleanup.get("passed"),
                     inv_lower_cleanup)
        require_true("lower cleanup restored_normal_gateway_runtime",
                     lower_cleanup.get("restored_normal_gateway_runtime"),
                     inv_lower_cleanup)
        require_true("lower cleanup zero_command_published",
                     lower_cleanup.get("zero_command_published"), inv_lower_cleanup)
        require_exact("lower cleanup normal_runtime_restoration_exit_code",
                      lower_cleanup.get("normal_runtime_restoration_exit_code"), 0,
                      inv_lower_cleanup)
        require_exact("lower cleanup verification_status",
                      lower_cleanup.get("verification_status"), 0, inv_lower_cleanup)
        if isinstance(checked, dict):
            restated = dict((key, lower_cleanup.get(key)) for key in checked)
            require(restated == checked,
                    "lower_layer.cleanup_checked does not restate the lower cleanup file",
                    inv_lower_cleanup)

    # --------------------------------------------------------------------------
    # 4. Freshness - not future, not stale
    # --------------------------------------------------------------------------
    inv_fresh = "evidence_not_future_and_within_max_age"
    now = _dt.datetime.now(_dt.timezone.utc)
    evidence_age = None
    if finished_at is not None:
        evidence_age = (now - finished_at).total_seconds()
        require(evidence_age >= 0,
                "evidence finished_at %s is in the future relative to %s"
                % (finished_at.isoformat(), now.isoformat()), inv_fresh)
        require(evidence_age <= max_age,
                "evidence is %.3fs old, older than the %ds maximum in force"
                % (evidence_age, max_age), inv_fresh)

    evidence_files = {
        "upper-report.json": upper_report_file,
        "upper-cleanup.json": upper_cleanup_file,
        "lower-evidence.json": lower_evidence_file,
        "lower-report.json": lower_report_file,
        "lower-cleanup.json": lower_cleanup_file,
    }
    now_epoch = now.timestamp()
    for name in sorted(evidence_files):
        entry = evidence_files[name]
        if entry is None:
            fail("evidence file %s was not readable" % name, inv_paths)
            continue
        if entry["mtime"] > now_epoch + 1.0:
            fail("evidence file %s has a future mtime: %s" % (name, entry["path"]),
                 inv_fresh)

    # --------------------------------------------------------------------------
    # 5. Copy all five evidence files into the durable Core result
    # --------------------------------------------------------------------------
    inv_copy = "five_evidence_files_copied_with_matching_hashes"
    copies = {}
    if all(evidence_files[name] is not None for name in evidence_files):
        for name in sorted(evidence_files):
            entry = evidence_files[name]
            destination = os.path.join(evidence_dir, name)
            with open(destination, "wb") as handle:
                handle.write(entry["bytes"])
                handle.flush()
                os.fsync(handle.fileno())
            copy_hash = sha256_file(destination)
            require_exact("evidence copy %s sha256" % name, copy_hash,
                          entry["sha256"], inv_copy)
            copies[name] = {
                "source_path": entry["path"],
                "source_sha256": entry["sha256"],
                "source_size_bytes": entry["size"],
                "copy_path": destination,
                "copy_sha256": copy_hash,
            }
        require(len(copies) == 5,
                "expected five copied evidence files, got %d" % len(copies), inv_copy)
    else:
        fail("not all five evidence files were readable; nothing was copied", inv_copy)

    state["copies"] = copies
    state["source_hashes"] = dict(
        (name, evidence_files[name]["sha256"])
        for name in sorted(evidence_files) if evidence_files[name] is not None)
    state["provenance_finished_at"] = provenance.get("finished_at")
    state["evidence_age_seconds"] = (
        round(evidence_age, 3) if evidence_age is not None else None)
    state["evidence_provenance"] = {
        "started_at": provenance.get("started_at"),
        "finished_at": provenance.get("finished_at"),
        "host_platform": provenance.get("host_platform"),
        "repo_commit": provenance.get("repo_commit"),
        "lower_repo_commit": provenance.get("lower_repo_commit"),
        "verifier_sha256": provenance.get("verifier_sha256"),
        "verifier_behavior_revision": provenance.get("verifier_behavior_revision"),
    }
    state["input"] = {
        "run_dir": run_dir,
        "run_dir_input": cfg["run_dir_input"],
        "run_dir_input_kind": cfg["run_dir_input_kind"],
        "run_id": run_id,
        "modules_repo": modules_repo,
        "lower_repo": lower_repo,
        "core_root": cfg["core_root"],
        "max_evidence_age_seconds": max_age,
        "max_evidence_age_source": cfg["max_age_source"],
    }
    state["lower"] = {
        "lower_run_id": lower_run_id,
        "lower_run_dir": lower_run_dir,
        "report": {
            "path": lower_report_path,
            "contract_version": LOWER_REPORT_CONTRACT,
            "declared_sha256": lower_layer.get("report_sha256"),
            "recomputed_sha256": (
                lower_report_file["sha256"] if lower_report_file else None),
        },
        "cleanup": {
            "path": lower_cleanup_path,
            "contract_version": LOWER_CLEANUP_CONTRACT,
            "declared_sha256": lower_layer.get("cleanup_sha256"),
            "recomputed_sha256": (
                lower_cleanup_file["sha256"] if lower_cleanup_file else None),
        },
        "cleanup_checked": checked if isinstance(checked, dict) else None,
    }
    state["plan_contract"] = plan_contract_facts

    # --------------------------------------------------------------------------
    # 6. Registration through the real public ModuleRegistry surface
    # --------------------------------------------------------------------------
    sys.path.insert(0, core_src)
    sys.path.insert(0, target)

    inv_ep = "exactly_one_robotics_entry_point"
    inv_dist = "robotics_distribution_identity_inside_target"
    inv_plugin = "robotics_plugin_loaded_without_discovery_error"
    inv_owned = "owned_module_ids_exactly_move_stop_turn"
    inv_origin = "import_origins_are_target_then_core_src"

    entry_points_seen = []
    discovery_errors = []
    executions = {}
    selected = {}

    from importlib.metadata import distributions

    seen_keys = set()
    for dist in distributions():
        try:
            dist_name = dist.metadata["Name"]
            dist_version = dist.version
            dist_location = os.path.realpath(str(dist.locate_file("")))
        except Exception:
            continue
        try:
            dist_entry_points = list(dist.entry_points or [])
        except Exception:
            continue
        for entry_point in dist_entry_points:
            if getattr(entry_point, "group", None) != ENTRY_POINT_GROUP:
                continue
            key = (dist_location, dist_name, entry_point.name, entry_point.value)
            if key in seen_keys:
                continue
            seen_keys.add(key)
            entry_points_seen.append({
                "group": ENTRY_POINT_GROUP,
                "name": entry_point.name,
                "value": entry_point.value,
                "distribution": dist_name,
                "distribution_version": dist_version,
                "distribution_location": dist_location,
            })
    entry_points_seen.sort(key=lambda item: (item["name"], str(item["distribution"]),
                                             item["distribution_location"]))

    # flyto-core legitimately ships its own `community` entry point, and any
    # other installed plugin is somebody else's correct business. The
    # requirement is that exactly one entry point is the robotics one - not that
    # robotics is alone in the group. Everything else is preserved and reported.
    robotics_eps = [ep for ep in entry_points_seen if ep["name"] == ENTRY_POINT_NAME]
    other_eps = [ep for ep in entry_points_seen if ep["name"] != ENTRY_POINT_NAME]

    if require(len(robotics_eps) == 1,
               "expected exactly one %r entry point in group %s, found %d"
               % (ENTRY_POINT_NAME, ENTRY_POINT_GROUP, len(robotics_eps)), inv_ep):
        selected = dict(robotics_eps[0])
        require_exact("robotics entry point value", selected["value"],
                      ENTRY_POINT_VALUE, inv_ep)
        normalised = str(selected["distribution"] or "").strip().lower().replace("_", "-")
        require_exact("robotics distribution name", normalised, DISTRIBUTION_NAME, inv_dist)
        require_exact("robotics distribution version",
                      selected["distribution_version"], DISTRIBUTION_VERSION, inv_dist)
        require_exact("robotics distribution metadata location",
                      selected["distribution_location"], target, inv_dist)

    from core.modules import ModuleRegistry

    registry_logger = logging.getLogger("core.modules.registry.core")

    class _ErrorCollector(logging.Handler):
        def emit(self, record):
            if record.levelno >= logging.ERROR:
                discovery_errors.append(record.getMessage())

    collector = _ErrorCollector(level=logging.ERROR)
    previous_level = registry_logger.level
    registry_logger.addHandler(collector)
    registry_logger.setLevel(logging.ERROR)
    try:
        ModuleRegistry.clear()
        ModuleRegistry.discover_plugins(force=True)
    finally:
        registry_logger.removeHandler(collector)
        registry_logger.setLevel(previous_level)

    for message in discovery_errors:
        if ENTRY_POINT_NAME in message:
            fail("plugin discovery reported an error for the robotics plugin: %s"
                 % message, inv_plugin)

    plugins = ModuleRegistry.get_plugins()
    plugins_reported = {}
    for name in sorted(plugins):
        info = plugins[name]
        plugins_reported[name] = {
            "version": getattr(info, "version", None),
            "module_count": getattr(info, "module_count", None),
            "entry_point": getattr(info, "entry_point", None),
        }

    owned_module_ids = []
    if require(ENTRY_POINT_NAME in plugins,
               "the robotics plugin did not load; discovered plugins: %s"
               % (sorted(plugins),), inv_plugin):
        info = plugins[ENTRY_POINT_NAME]
        require_exact("robotics plugin version", getattr(info, "version", None),
                      DISTRIBUTION_VERSION, inv_plugin)
        require_exact("robotics plugin entry point", getattr(info, "entry_point", None),
                      ENTRY_POINT_VALUE, inv_plugin)
        require_exact("robotics plugin module_count",
                      getattr(info, "module_count", None), len(EXPECTED_MODULE_IDS),
                      inv_owned)
        owned_module_ids = sorted(ModuleRegistry.get_plugin_modules(ENTRY_POINT_NAME))
        require_exact("robotics owned module ids", owned_module_ids,
                      EXPECTED_MODULE_IDS, inv_owned)

    import flyto_modules_robotics as robotics_package
    import core as core_package
    import_origins = {
        "flyto_modules_robotics": os.path.realpath(robotics_package.__file__ or ""),
        "core": os.path.realpath(core_package.__file__ or ""),
        "sys_path_head": list(sys.path[:2]),
    }
    require(import_origins["flyto_modules_robotics"].startswith(target + os.sep),
            "flyto_modules_robotics was imported from outside the install target: %s"
            % import_origins["flyto_modules_robotics"], inv_origin)
    require(import_origins["core"].startswith(core_src + os.sep),
            "core was imported from outside this checkout: %s"
            % import_origins["core"], inv_origin)
    require(sys.path[0] == target and sys.path[1] == core_src,
            "sys.path does not put the install target first and this Core src second: %s"
            % (sys.path[:2],), inv_origin)

    state["import_origins"] = import_origins
    state["discovery_errors"] = list(discovery_errors)
    state["registration"] = {
        "entry_point_group": ENTRY_POINT_GROUP,
        "entry_points_in_group": entry_points_seen,
        "other_entry_points_preserved": other_eps,
        "selected_entry_point": selected,
        "plugins": plugins_reported,
        "discovery_errors": list(discovery_errors),
        "owned_module_ids": owned_module_ids,
        "registry_api_used": [
            "ModuleRegistry.clear",
            "ModuleRegistry.discover_plugins",
            "ModuleRegistry.get_plugins",
            "ModuleRegistry.get_plugin_modules",
            "ModuleRegistry.execute",
        ],
        "modules_were_never_instantiated_directly": True,
    }

    # --------------------------------------------------------------------------
    # 7. Declaration-only execution of each owned module
    # --------------------------------------------------------------------------
    if owned_module_ids == EXPECTED_MODULE_IDS:
        for module_id in EXPECTED_MODULE_IDS:
            params = dict(MODULE_PARAMS[module_id])
            context = dict(CONTEXT)
            try:
                result = asyncio.run(ModuleRegistry.execute(module_id, params, context))
            except NonActuatingViolation as exc:
                fail("%s attempted to act on the world: %s" % (module_id, exc),
                     "declarations_are_not_dispatched")
                continue
            except Exception as exc:
                fail("%s raised during declaration-only execution: %r"
                     % (module_id, exc), "declarations_are_not_dispatched")
                continue
            require_exact("%s: execution context after the call" % module_id,
                          context, {"resource_id": DEVICE_ID},
                          "execution_context_unchanged")
            executions[module_id] = inspect_declaration(module_id, params, result,
                                                        plan_schema)

    state["executions"] = executions
    return build_report(cfg, started_at, state)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
