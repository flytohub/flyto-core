def inspect_declaration(module_id, params, result, plan_schema):
    """Check one module result is a plan declaration and nothing more."""
    payload = result
    # Modules answer with the Core success envelope; the declaration is inside.
    for _ in range(4):
        if isinstance(payload, dict) and "data" in payload and "dispatched" not in payload:
            payload = payload["data"]
        else:
            break

    dispatched = find_key(payload, "dispatched")
    if require(len(dispatched) >= 1,
               "%s: result declares no `dispatched` field" % module_id,
               "declarations_are_not_dispatched"):
        for path, value in dispatched:
            require_false("%s: %s" % (module_id, path), value,
                          "declarations_are_not_dispatched")

    device = find_key(payload, "requires_device")
    if require(len(device) >= 1,
               "%s: result declares no `requires_device` field" % module_id,
               "declarations_bound_to_synthetic_device"):
        for path, value in device:
            require_exact("%s: %s" % (module_id, path), value, DEVICE_ID,
                          "declarations_bound_to_synthetic_device")

    requests = find_contract_objects(payload, REQUEST_CONTRACT)
    require(len(requests) == 1,
            "%s: expected exactly one %s object, found %d"
            % (module_id, REQUEST_CONTRACT, len(requests)),
            "requests_use_plan_run_request_v1")

    plans = find_contract_objects(payload, PLAN_CONTRACT)
    require(len(plans) == 1,
            "%s: expected exactly one %s object, found %d"
            % (module_id, PLAN_CONTRACT, len(plans)),
            "plans_satisfy_plan_v1_schema")

    plan = plans[0][1] if len(plans) == 1 else {}
    if len(requests) == 1 and len(plans) == 1:
        require(plans[0][0].startswith(requests[0][0]),
                "%s: the plan is not carried inside the plan-run request (%s vs %s)"
                % (module_id, plans[0][0], requests[0][0]),
                "requests_use_plan_run_request_v1")

    if not plan:
        schema_errors = ["$.plan: no %s object was produced" % PLAN_CONTRACT]
    elif plan_schema is None:
        schema_errors = ["$.plan: the canonical %s schema could not be loaded"
                         % PLAN_CONTRACT]
    else:
        try:
            schema_errors = validate_schema(plan, plan_schema, plan_schema, "$.plan", [])
        except SchemaError as exc:
            schema_errors = ["$.plan: %s" % exc]
    for message in schema_errors:
        fail("%s: plan does not satisfy %s: %s" % (module_id, PLAN_CONTRACT, message),
             "plans_satisfy_plan_v1_schema")

    require_exact("%s: plan.robot_id" % module_id, plan.get("robot_id"), DEVICE_ID,
                  "declarations_bound_to_synthetic_device")

    steps = plan.get("steps") if isinstance(plan.get("steps"), list) else []
    require(len(steps) >= 1, "%s: plan has no steps" % module_id,
            "plans_satisfy_plan_v1_schema")

    final_capability = None
    if steps and isinstance(steps[-1], dict):
        final_capability = steps[-1].get("capability")
    require_exact("%s: final step capability" % module_id, final_capability, SAFE_STOP,
                  "plans_end_with_safe_stop")

    # Nothing in a declaration may name a host, URL, endpoint or URI. A plan that
    # knows where to go is a plan that could be persuaded to go there.
    for path, value in walk(payload):
        if isinstance(value, dict):
            for key in value:
                if isinstance(key, str) and key.lower() in HOSTISH_KEYS:
                    fail("%s: declaration exposes a host-like key at %s.%s"
                         % (module_id, path, key),
                         "declarations_contain_no_host_url_or_uri")
        if isinstance(value, str) and "://" in value:
            fail("%s: declaration embeds a URI at %s: %r" % (module_id, path, value),
                 "declarations_contain_no_host_url_or_uri")

    return {
        "params": params,
        "context": dict(CONTEXT),
        "dispatched_occurrences": [
            {"path": path, "value": value} for path, value in dispatched],
        "requires_device_occurrences": [
            {"path": path, "value": value} for path, value in device],
        "request_contract_version": (
            requests[0][1].get("contract_version") if len(requests) == 1 else None),
        "request_path": requests[0][0] if len(requests) == 1 else None,
        "plan_contract_version": plan.get("contract_version"),
        "plan_id": plan.get("plan_id"),
        "plan_robot_id": plan.get("robot_id"),
        "plan_step_count": len(steps),
        "plan_step_capabilities": [
            step.get("capability") for step in steps if isinstance(step, dict)],
        "final_step_capability": final_capability,
        "plan_schema_violations": schema_errors,
    }


